type groupJournalAuthority struct{ t *Tx }

func (t *Tx) FleetGroupJournalAuthority() g.ContinuationAuthority { return groupJournalAuthority{t} }
func (a groupJournalAuthority) Current(ctx context.Context, chain string) (g.ContinuationCursor, error) {
	return a.t.FleetGroupJournalCursor(ctx, chain)
}
func (a groupJournalAuthority) LookupIdentity(ctx context.Context, chain string, anchor g.ContinuationIdentityAnchor, key g.ContinuationIdentityKey) (g.ContinuationIdentity, bool, error) {
	var entry g.ContinuationIdentity
	c, err := a.Current(ctx, chain)
	if err != nil {
		return entry, false, err
	}
	if anchor.ChainID != chain || anchor.Count > c.Identities.Count {
		return entry, false, ErrGroupJournalInvalid
	}
	var published bool
	err = a.t.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM public.fleet_group_journal_heads WHERE tenant_id=$1 AND chain_id=$2 AND cursor_document->'identities'->>'sha256'=$3 AND (cursor_document->'identities'->>'count')::numeric=$4)`, a.t.Tenant, chain, anchor.SHA256, fmt.Sprint(anchor.Count)).Scan(&published)
	if err != nil {
		return entry, false, err
	}
	if !published {
		e, eerr := a.t.groupJournalChain(ctx, chain)
		if eerr != nil {
			return entry, false, eerr
		}
		if anchor != g.ContinuationIdentityBase(e) {
			return entry, false, ErrGroupJournalInvalid
		}
	}
	var hash string
	err = a.t.QueryRow(ctx, `SELECT content_hash FROM public.fleet_group_journal_identities WHERE tenant_id=$1 AND chain_id=$2 AND namespace=$3 AND identity=$4 AND ordinal<=$5`, a.t.Tenant, chain, key.Namespace, key.ID, fmt.Sprint(anchor.Count)).Scan(&hash)
	if errors.Is(err, pgx.ErrNoRows) {
		return entry, false, nil
	}
	if err != nil {
		return entry, false, err
	}
	return g.ContinuationIdentity{Key: key, SHA256: hash}, true, nil
}
func (t *Tx) groupJournalChain(ctx context.Context, chain string) (g.ContinuationEnvelope, error) {
	var e g.ContinuationEnvelope
	var raw []byte
	err := t.QueryRow(ctx, `SELECT raw_document FROM public.fleet_group_journal_chain_authorizations WHERE tenant_id=$1 AND chain_id=$2`, t.Tenant, chain).Scan(&raw)
	if err == nil {
		err = groupJournalDecode(raw, &e)
	}
	return e, err
}

// All public mutation methods operate within the caller's transaction. No
// network call is made here, and callers must roll back on any returned error.
// Transitions are generated by the pinned reducer, never accepted from HTTP.
func (t *Tx) groupJournalOpenContinuation(ctx context.Context, chain string, key ed25519.PrivateKey, nonce string) (g.ContinuationCursor, error) {
	v, keys, err := t.FleetGroupJournalOriginal(ctx, chain)
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	e, err := t.groupJournalChain(ctx, chain)
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	next, err := g.OpenContinuationFromJournal(ctx, v, e, keys.Core(), t.FleetGroupJournalAuthority(), key, nonce, time.Now().UTC())
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	return t.groupJournalCommitContinuation(ctx, next, nil)
}
func (t *Tx) groupJournalContinuation(ctx context.Context, chain string, allowStale bool) (g.ContinuationView, FleetGroupJournalKeys, error) {
	var v g.ContinuationView
	c, err := t.FleetGroupJournalCursor(ctx, chain)
	if err != nil {
		return v, FleetGroupJournalKeys{}, err
	}
	b, err := t.groupJournalRoot(ctx, chain)
	if err != nil {
		return v, b.Keys, err
	}
	if c.Kind != g.ContinuationSegment {
		return v, b.Keys, ErrGroupJournalConflict
	}
	v.Origin = g.ContinuationOrigin{Parent: b.Parent, Authorization: b.Authorization}
	if v.Authorization, err = t.groupJournalChain(ctx, chain); err != nil {
		return v, b.Keys, err
	}
	var raw []byte
	if err = t.QueryRow(ctx, `SELECT raw_document FROM public.fleet_group_journal_segments WHERE tenant_id=$1 AND chain_id=$2 AND segment=$3`, t.Tenant, chain, fmt.Sprint(c.Segment)).Scan(&raw); err != nil {
		return v, b.Keys, err
	}
	if err = groupJournalDecode(raw, &v.Checkpoint); err != nil {
		return v, b.Keys, err
	}
	v.Records = []g.ContinuationRecord{}
	rows, err := t.Query(ctx, `SELECT raw_document FROM public.fleet_group_journal_records WHERE tenant_id=$1 AND chain_id=$2 AND segment=$3 ORDER BY sequence`, t.Tenant, chain, fmt.Sprint(c.Segment))
	if err != nil {
		return v, b.Keys, err
	}
	for rows.Next() {
		var r g.ContinuationRecord
		if err = rows.Scan(&raw); err != nil {
			break
		}
		if err = groupJournalDecode(raw, &r); err != nil {
			break
		}
		v.Records = append(v.Records, r)
	}
	if err == nil {
		err = rows.Err()
	}
	rows.Close()
	if err != nil {
		return v, b.Keys, err
	}
	if err = t.QueryRow(ctx, `SELECT raw_document FROM public.fleet_group_journal_heads WHERE tenant_id=$1 AND chain_id=$2 AND content_hash=$3`, t.Tenant, chain, c.HeadSHA256).Scan(&raw); err != nil {
		return v, b.Keys, err
	}
	if err = groupJournalDecode(raw, &v.Head); err != nil {
		return v, b.Keys, err
	}
	at := time.Now().UTC()
	if allowStale {
		at = v.Head.Head.ObservedAt
	}
	_, err = g.VerifyContinuation(ctx, v, b.Keys.Core(), t.FleetGroupJournalAuthority(), at)
	return v, b.Keys, err
}
func (t *Tx) FleetGroupJournalContinuation(ctx context.Context, chain string) (g.ContinuationView, FleetGroupJournalKeys, error) {
	return t.groupJournalContinuation(ctx, chain, false)
}
func (t *Tx) groupJournalRotate(ctx context.Context, chain string, key ed25519.PrivateKey, nonce string) (g.ContinuationCursor, error) {
	v, keys, err := t.FleetGroupJournalContinuation(ctx, chain)
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	next, err := g.RotateContinuation(ctx, v, keys.Core(), t.FleetGroupJournalAuthority(), key, nonce, time.Now().UTC())
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	return t.groupJournalCommitContinuation(ctx, next, nil)
}
func (t *Tx) groupJournalAppendContinuation(ctx context.Context, chain string, expected g.ContinuationCursor, key ed25519.PrivateKey, r g.ContinuationRecord) (g.ContinuationCursor, bool, error) {
	c, err := t.FleetGroupJournalCursor(ctx, chain)
	if err != nil {
		return c, false, err
	}
	v, keys, err := t.FleetGroupJournalContinuation(ctx, chain)
	if err != nil {
		return c, false, err
	}
	if r.Receipt != nil {
		if err = t.groupJournalRequireInbox(ctx, chain, g.ContinuationSegment, r.Receipt.Receipt.ID, *r.Receipt); err != nil {
			return c, false, err
		}
	}
	if r.OriginalReceipt != nil {
		if err = t.groupJournalRequireInbox(ctx, chain, g.ContinuationOriginal, r.OriginalReceipt.Receipt.ID, *r.OriginalReceipt); err != nil {
			return c, false, err
		}
	}
	next, err := g.AppendContinuationRecord(ctx, v, keys.Core(), t.FleetGroupJournalAuthority(), key, r, time.Now().UTC())
	if err != nil {
		return c, false, err
	}
	if next.Replayed {
		return c, true, nil
	}
	if c != expected {
		return c, false, ErrGroupJournalConflict
	}
	c, err = t.groupJournalCommitContinuation(ctx, next, &r)
	return c, false, err
}
func (t *Tx) groupJournalRenewContinuation(ctx context.Context, chain string, key ed25519.PrivateKey) (g.ContinuationCursor, error) {
	v, keys, err := t.groupJournalContinuation(ctx, chain, true)
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	next, err := g.RenewContinuationHead(ctx, v, keys.Core(), t.FleetGroupJournalAuthority(), key, time.Now().UTC())
	if err != nil {
		return g.ContinuationCursor{}, err
	}
	return t.groupJournalCommitContinuation(ctx, next, nil)
}
func (t *Tx) groupJournalCommitContinuation(ctx context.Context, tr g.ContinuationTransition, record *g.ContinuationRecord) (g.ContinuationCursor, error) {
	c, err := t.FleetGroupJournalCursor(ctx, tr.Expected.ChainID)
	if err != nil {
		return c, err
	}
	if c != tr.Expected {
		return c, ErrGroupJournalConflict
	}
	if tr.Next.Segment > c.Segment {
		raw, h, e := groupJournalBytes(tr.View.Checkpoint)
		if e != nil {
			return c, e
		}
		_, err = t.Exec(ctx, `INSERT INTO public.fleet_group_journal_segments(tenant_id,chain_id,segment,kind,checkpoint_hash,document,raw_document) VALUES($1,$2,$3,'RECOVERY_SEGMENT',$4,convert_from($5::bytea,'UTF8')::jsonb,$5)`, t.Tenant, c.ChainID, fmt.Sprint(tr.Next.Segment), h, raw)
		if err != nil {
			return c, err
		}
	}
	anchor := c.Identities
	if c.Kind == g.ContinuationOriginal {
		anchor = g.ContinuationIdentityBase(tr.View.Authorization)
	}
	for _, entry := range tr.Identities {
		step, _, e := groupJournalBytes(struct {
			Previous string
			Entry    g.ContinuationIdentity
		}{anchor.SHA256, entry})
		if e != nil {
			return c, e
		}
		anchor, err = g.ContinuationIdentityExtend(anchor, entry)
		if err != nil {
			return c, err
		}
		_, err = t.Exec(ctx, `INSERT INTO public.fleet_group_journal_identities(tenant_id,chain_id,namespace,identity,ordinal,content_hash,root_hash,raw_step) VALUES($1,$2,$3,$4,$5,$6,$7,$8)`, t.Tenant, c.ChainID, entry.Key.Namespace, entry.Key.ID, fmt.Sprint(anchor.Count), entry.SHA256, anchor.SHA256, step)
		if err != nil {
			return c, err
		}
	}
	if anchor != tr.Next.Identities {
		return c, ErrGroupJournalInvalid
	}
	if record != nil {
		if err = t.groupJournalRecordInsert(ctx, c, record.Kind, *record, tr.View.Head); err != nil {
			return c, err
		}
		if record.Kind == g.ContinuationPreparing && record.Command != nil {
			command := *record.Command
			raw, hash, e := groupJournalBytes(command)
			if e != nil {
				return c, e
			}
			_, err = t.Exec(ctx, `INSERT INTO public.fleet_group_journal_operations(tenant_id,chain_id,command_id,operation_id,fence,command_hash,document,raw_document) VALUES($1,$2,$3,$4,$5,$6,convert_from($7::bytea,'UTF8')::jsonb,$7)`, t.Tenant, c.ChainID, command.ID, command.OperationID, fmt.Sprint(command.Fence), hash, raw)
			if err != nil {
				return c, err
			}
			if err = t.groupJournalReserve(ctx, c.ChainID, false, hash); err != nil {
				return c, err
			}
		}
	}
	if err = t.groupJournalHeadInsert(ctx, tr.Next, tr.View.Head, tr.Projection); err != nil {
		return c, err
	}
	if err = t.groupJournalCAS(ctx, c, tr.Next); err != nil {
		return c, err
	}
	if record != nil && tr.Projection.Pending != nil {
		action := ""
		switch record.Kind {
		case g.ContinuationPreparing:
			if tr.Projection.Pending.Command.Mode == g.ContinuationInverse {
				action = "GIT_ADVANCE"
			}
		case g.ContinuationIntent:
			action = "APPLY"
			if tr.Projection.Pending.Command.Mode == g.ContinuationRepair {
				action = "GIT_REPAIR"
			}
		case g.ContinuationUnknown:
			action = "RECONCILE"
		}
		if action != "" {
			if err = t.groupJournalQueue(ctx, tr.Next, tr.Projection.Pending.Command.ID, action, tr.Projection.Pending.Command); err != nil {
				return c, err
			}
		}
	}
	if record != nil && record.Receipt != nil {
		if err = t.groupJournalFinishDelivery(ctx, c.ChainID, record.Receipt.Receipt.CommandID, record.Receipt.Receipt.Kind); err != nil {
			return c, err
		}
	}
	if record != nil && record.OriginalReceipt != nil {
		if err = t.groupJournalFinishDelivery(ctx, c.ChainID, record.OriginalReceipt.Receipt.CommandID, record.OriginalReceipt.Receipt.Kind); err != nil {
			return c, err
		}
	}
	return tr.Next, nil
}
