func HealthReceiptSHA256(r HealthReceipt) string { r.SHA256 = ""; return g.Digest(r) }

type HealthCollector struct {
	mu           sync.Mutex
	installation HealthInstallation
	client       *http.Client
	sequence     uint64
	previous     string
	last         *HealthSnapshot
	lastCapture  time.Time
}

func NewHealthCollector(in HealthInstallation) (*HealthCollector, error) {
	u, err := url.Parse(in.TargetURL)
	if err != nil || in.ID == "" || !in.Binding.valid() || u.Scheme != "http" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || u.Path != "" || u.Port() == "" {
		return nil, ErrHealth
	}
	ip := net.ParseIP(u.Hostname())
	if ip == nil || !ip.IsLoopback() {
		return nil, ErrHealth
	}
	transport := &http.Transport{Proxy: nil, DisableKeepAlives: false, MaxConnsPerHost: 64}
	return &HealthCollector{installation: in, client: &http.Client{Timeout: 15 * time.Second, Transport: transport, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}, nil
}

func (c *HealthCollector) snapshot(ctx context.Context) (HealthSnapshot, error) {
	req, _ := http.NewRequestWithContext(ctx, http.MethodGet, c.installation.TargetURL+"/snapshot", nil)
	res, err := c.client.Do(req)
	if err != nil {
		return HealthSnapshot{}, ErrHealth
	}
	defer res.Body.Close()
	var s HealthSnapshot
	decoder := json.NewDecoder(io.LimitReader(res.Body, 8193))
	decoder.DisallowUnknownFields()
	if res.StatusCode != 200 || decoder.Decode(&s) != nil || decoder.Decode(new(any)) != io.EOF || !s.Heartbeat || s.InstanceID == "" || s.Sequence == 0 || s.BindingSHA256 != g.Digest(c.installation.Binding) || s.Definition != HealthCompletedOperation || time.Since(s.CapturedAt) < -time.Second || time.Since(s.CapturedAt) > 5*time.Second {
		return HealthSnapshot{}, ErrHealth
	}
	return s, nil
}

// Collect measures a bounded actual interval; it never extends timestamps to
// a requested observation duration. Receipts are sequential and append-only.
// The surrounding worker archives their exact bytes before using references.
func (c *HealthCollector) Collect(ctx context.Context, requests, parallelism int) (HealthReceipt, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if requests < 1 || requests > 4096 || parallelism < 1 || parallelism > 64 {
		return HealthReceipt{}, ErrHealth
	}
	ctx, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()
	var before HealthSnapshot
	var err error
	var captureStart time.Time
	if c.last != nil {
		// Carry the actual previous heartbeat boundary forward. Counter closure
		// below rejects any unobserved external work in the intervening time.
		if time.Since(c.last.CapturedAt) > time.Minute {
			return HealthReceipt{}, ErrHealth
		}
		before = *c.last
		captureStart = c.lastCapture
	} else {
		before, err = c.snapshot(ctx)
		if err != nil {
			return HealthReceipt{}, err
		}
		captureStart = time.Now()
	}
	observations := make([]HealthObservation, requests)
	jobs := make(chan int)
	var workers sync.WaitGroup
	for n := 0; n < parallelism; n++ {
		workers.Add(1)
		go func() {
			defer workers.Done()
			for index := range jobs {
				start := time.Now()
				req, _ := http.NewRequestWithContext(ctx, http.MethodPost, c.installation.TargetURL+"/work", nil)
				res, transportErr := c.client.Do(req)
				status := 0
				var readErr error
				if transportErr == nil {
					status = res.StatusCode
					_, readErr = io.Copy(io.Discard, io.LimitReader(res.Body, 8193))
					_ = res.Body.Close()
				}
				end := time.Now()
				// Latency uses Go's monotonic clock; original UTC endpoints and
				// their disagreement remain immutable clock-quality evidence.
				clock := healthClock(start, end)
				observations[index] = HealthObservation{StartedAt: start.UTC(), FinishedAt: end.UTC(), ElapsedNS: clock.ElapsedNS, StatusCode: status, TransportError: transportErr != nil, ReadError: readErr != nil, Clock: &clock}
			}
		}()
	}
	for n := 0; n < requests; n++ {
		jobs <- n
	}
	close(jobs)
	workers.Wait()
	captureEnd := time.Now()
	after, err := c.snapshot(ctx)
	if err != nil {
		return HealthReceipt{}, err
	}
	if after.CapturedAt.Sub(before.CapturedAt) > time.Minute {
		return HealthReceipt{}, ErrHealth
	}
	c.sequence++
	clock := healthClock(captureStart, captureEnd)
	r := HealthReceipt{SchemaVersion: "2", InstallationID: c.installation.ID, Binding: c.installation.Binding, Sequence: c.sequence, PreviousSHA256: c.previous, Before: before, After: after, Observations: observations, MeasurementRevision: healthMeasurementV2, Clock: &clock}
	r.SHA256 = HealthReceiptSHA256(r)
	c.previous = r.SHA256
	copyAfter := after
	c.last = &copyAfter
	c.lastCapture = time.Now()
	return r, nil
}

