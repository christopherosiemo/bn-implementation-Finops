var ErrHealth = errors.New("GROUP_FIXTURE_HEALTH_EVIDENCE_INVALID")

const HealthCompletedOperation = "ISOLATED_HTTP_COMPLETED_OPERATION"

// HealthBinding is selected by the private installation and ledger worker.
// Neither this binding nor a local HTTP observation confers customer authority.
type HealthBinding struct {
	Binding       g.Binding `json:"binding"`
	Realm         g.Realm   `json:"realm"`
	ProgramSHA256 string    `json:"program_sha256"`
	CommandID     string    `json:"command_id"`
	OperationID   string    `json:"operation_id"`
	Fence         uint64    `json:"fence"`
}

func (b HealthBinding) valid() bool {
	return g.ValidateBinding(b.Binding) == nil && g.ValidateRealm(b.Realm) == nil && validHealthHash(b.ProgramSHA256) && b.CommandID != "" && b.OperationID != "" && b.Fence > 0
}
func validHealthHash(s string) bool {
	raw, err := hex.DecodeString(s)
	return err == nil && len(raw) == 32 && strings.ToLower(s) == s
}

// Counters are generated by the instrumented server, not inferred from client
// status codes. Completed means this fixture's work function returned success;
// it makes no claim about customer business-work semantics.
type HealthSnapshot struct {
	InstanceID        string    `json:"instance_id"`
	BindingSHA256     string    `json:"binding_sha256"`
	Definition        string    `json:"definition"`
	CapturedAt        time.Time `json:"captured_at"`
	Sequence          uint64    `json:"sequence"`
	PeakSinceSequence uint64    `json:"peak_since_sequence"`
	Accepted          uint64    `json:"accepted"`
	Completed         uint64    `json:"completed"`
	Rejected          uint64    `json:"rejected"`
	Failed            uint64    `json:"failed"`
	Backlog           uint64    `json:"backlog"`
	InFlight          uint64    `json:"inflight"`
	PeakBacklog       uint64    `json:"peak_backlog"`
	PeakInFlight      uint64    `json:"peak_inflight"`
	Heartbeat         bool      `json:"heartbeat"`
}

type HTTPHealthFixture struct {
	mu         sync.Mutex
	work       func(context.Context) error
	slots      chan struct{}
	maxBacklog uint64
	state      HealthSnapshot
}

func NewHTTPHealthFixture(binding HealthBinding, work func(context.Context) error, maxInFlight, maxBacklog int) (*HTTPHealthFixture, error) {
	if !binding.valid() || work == nil || maxInFlight < 1 || maxInFlight > 1024 || maxBacklog < 0 || maxBacklog > 4096 {
		return nil, ErrHealth
	}
	var id [16]byte
	if _, err := rand.Read(id[:]); err != nil {
		return nil, err
	}
	return &HTTPHealthFixture{work: work, slots: make(chan struct{}, maxInFlight), maxBacklog: uint64(maxBacklog), state: HealthSnapshot{InstanceID: hex.EncodeToString(id[:]), BindingSHA256: g.Digest(binding), Definition: HealthCompletedOperation, Heartbeat: true}}, nil
}

func (f *HTTPHealthFixture) snapshot() HealthSnapshot {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.state.Sequence++
	out := f.state
	out.CapturedAt = time.Now().UTC()
	// This heartbeat atomically closes the preceding peak interval and starts
	// a new one. An unexpected reader changes the sequence and fails closure;
	// old saturation never contaminates a fresh owned-recovery interval.
	f.state.PeakSinceSequence = out.Sequence
	f.state.PeakBacklog = f.state.Backlog
	f.state.PeakInFlight = f.state.InFlight
	return out
}

func (f *HTTPHealthFixture) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	if r.URL.RawQuery != "" || r.ContentLength > 0 || r.TransferEncoding != nil {
		http.Error(w, "invalid request", http.StatusBadRequest)
		return
	}
	if r.Method == http.MethodGet && r.URL.Path == "/snapshot" {
		_ = json.NewEncoder(w).Encode(f.snapshot())
		return
	}
	if r.Method != http.MethodPost || r.URL.Path != "/work" {
		http.NotFound(w, r)
		return
	}
	f.mu.Lock()
	queued := false
	select {
	case f.slots <- struct{}{}:
	default:
		if f.state.Backlog >= f.maxBacklog {
			f.state.Rejected++
			f.mu.Unlock()
			w.WriteHeader(http.StatusTooManyRequests)
			_, _ = io.WriteString(w, `{"status":"rejected"}`)
			return
		}
		f.state.Backlog++
		queued = true
		if f.state.Backlog > f.state.PeakBacklog {
			f.state.PeakBacklog = f.state.Backlog
		}
	}
	f.state.Accepted++
	f.mu.Unlock()
	if queued {
		select {
		case f.slots <- struct{}{}:
		case <-r.Context().Done():
			f.mu.Lock()
			f.state.Backlog--
			f.state.Failed++
			f.mu.Unlock()
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
	}
	f.mu.Lock()
	if queued {
		f.state.Backlog--
	}
	f.state.InFlight++
	if f.state.InFlight > f.state.PeakInFlight {
		f.state.PeakInFlight = f.state.InFlight
	}
	f.mu.Unlock()
	err := f.work(r.Context())
	f.mu.Lock()
	f.state.InFlight--
	if err == nil {
		f.state.Completed++
	} else {
		f.state.Failed++
	}
	f.mu.Unlock()
	<-f.slots
	if err != nil {
		w.WriteHeader(http.StatusServiceUnavailable)
	}
	_, _ = io.WriteString(w, `{"status":"finished"}`)
}

