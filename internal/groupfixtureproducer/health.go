type healthPopulation struct {
	latencies                                                []int64
	errors, total                                            int64
	accepted, completed, rejected, failed, backlog, inflight uint64
	refs                                                     []string
	first, last                                              time.Time
	complete                                                 bool
	schema                                                   string
	monotonicNS                                              int64
}

func population(receipts []HealthReceipt, binding HealthBinding, baseline bool) (healthPopulation, error) {
	p := healthPopulation{complete: len(receipts) > 0}
	if len(receipts) > 4096 {
		return p, ErrHealth
	}
	var previous *HealthReceipt
	for i := range receipts {
		r := &receipts[i]
		if (r.SchemaVersion != "1" && r.SchemaVersion != "2") || !r.Binding.valid() || r.InstallationID == "" || !validHealthHash(r.SHA256) || HealthReceiptSHA256(*r) != r.SHA256 || g.Digest(r.Binding.Binding) != g.Digest(binding.Binding) || r.Binding.Realm != binding.Realm || r.Binding.ProgramSHA256 != binding.ProgramSHA256 || (!baseline && r.Binding != binding) {
			return p, ErrHealth
		}
		if i == 0 {
			p.schema = r.SchemaVersion
		} else if p.schema != r.SchemaVersion {
			return p, ErrHealth
		}
		if r.SchemaVersion == "1" {
			if r.MeasurementRevision != "" || r.Clock != nil {
				return p, ErrHealth
			}
		} else {
			if r.MeasurementRevision != healthMeasurementV2 || !validHealthClock(r.Clock) || r.Clock.StartedAt.Before(r.Before.CapturedAt) || r.Clock.FinishedAt.After(r.After.CapturedAt) || (previous != nil && r.Clock.StartedAt.Before(previous.Clock.FinishedAt)) {
				return p, errHealthClock
			}
			p.monotonicNS += r.Clock.ElapsedNS
		}
		b, a := r.Before, r.After
		if !b.Heartbeat || !a.Heartbeat || b.InstanceID == "" || b.InstanceID != a.InstanceID || b.Definition != HealthCompletedOperation || a.Definition != b.Definition || b.BindingSHA256 != g.Digest(r.Binding) || a.BindingSHA256 != b.BindingSHA256 || b.Sequence >= a.Sequence || !a.CapturedAt.After(b.CapturedAt) || a.CapturedAt.Sub(b.CapturedAt) > time.Minute || a.Accepted < b.Accepted || a.Completed < b.Completed || a.Rejected < b.Rejected || a.Failed < b.Failed || len(r.Observations) == 0 || len(r.Observations) > 4096 {
			return p, ErrHealth
		}
		if a.PeakSinceSequence != b.Sequence || a.PeakBacklog < a.Backlog || a.PeakBacklog < b.Backlog || a.PeakInFlight < a.InFlight || a.PeakInFlight < b.InFlight {
			return p, ErrHealth
		}
		if !healthSum(a.Accepted, a.Completed, a.Failed, a.Backlog, a.InFlight) || !healthSum(b.Accepted, b.Completed, b.Failed, b.Backlog, b.InFlight) || !healthSum(uint64(len(r.Observations)), a.Accepted-b.Accepted, a.Rejected-b.Rejected) {
			return p, ErrHealth
		}
		if previous != nil {
			if r.InstallationID != previous.InstallationID || b.InstanceID != previous.After.InstanceID || r.Sequence != previous.Sequence+1 || r.PreviousSHA256 != previous.SHA256 || b.CapturedAt.Before(previous.After.CapturedAt) {
				return p, ErrHealth
			}
			if b != previous.After {
				p.complete = false
			}
		} else {
			p.first = b.CapturedAt
		}
		for _, o := range r.Observations {
			if o.StartedAt.Before(b.CapturedAt) || o.FinishedAt.After(a.CapturedAt) || o.FinishedAt.Before(o.StartedAt) || o.ElapsedNS <= 0 || o.StatusCode < 0 || o.StatusCode > 599 {
				return p, ErrHealth
			}
			if err := healthObservationClock(r.SchemaVersion, o); err != nil {
				return p, err
			}
			p.total++
			if p.total > 250000 {
				return p, ErrHealth
			}
			if o.TransportError || o.ReadError || o.StatusCode < 200 || o.StatusCode >= 300 {
				p.errors++
			}
			if o.TransportError || o.ReadError || o.StatusCode == 0 {
				p.complete = false
			} else {
				p.latencies = append(p.latencies, o.ElapsedNS)
			}
		}
		p.accepted += a.Accepted - b.Accepted
		p.completed += a.Completed - b.Completed
		p.rejected += a.Rejected - b.Rejected
		p.failed += a.Failed - b.Failed
		p.backlog = a.Backlog
		p.inflight = a.InFlight
		if a.PeakBacklog > p.backlog {
			p.backlog = a.PeakBacklog
		}
		if a.PeakInFlight > p.inflight {
			p.inflight = a.PeakInFlight
		}
		p.refs = append(p.refs, r.SHA256)
		p.last = a.CapturedAt
		previous = r
		if b.Backlog != 0 || b.InFlight != 0 || a.Backlog != 0 || a.InFlight != 0 {
			p.complete = false
		}
	}
	return p, nil
}

func healthSum(expected uint64, values ...uint64) bool {
	total := uint64(0)
	for _, value := range values {
		if ^uint64(0)-total < value {
			return false
		}
		total += value
	}
	return total == expected
}

func healthQuantile(values []int64, percent int) *int64 {
	if len(values) == 0 {
		return nil
	}
	sorted := append([]int64(nil), values...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i] < sorted[j] })
	result := sorted[(len(sorted)*percent+99)/100-1]
	return &result
}
func exceedsRegression(current, baseline int64) bool {
	a := new(big.Int).Mul(big.NewInt(current), big.NewInt(100))
	b := new(big.Int).Mul(big.NewInt(baseline), big.NewInt(115))
	return a.Cmp(b) > 0
}

// EvaluateHealthWindow is observational only. A measured breach can terminate
// a canary early. Positive health requires the unshortened stage duration and
// receipt coverage; an installed FIXTURE_* descriptor cannot be an input here.
func EvaluateHealthWindow(binding HealthBinding, stage g.Stage, start time.Time, baseline, current []HealthReceipt, limits HealthLimits, now time.Time) HealthWindow {
	return evaluateHealthWindow(binding, stage, start, baseline, current, limits, now, false)
}

// EvaluateManifestHealthWindow accepts only an exact approved manifest entry.
// Capacity preparation has its own signed120second observation; it does not
// replace the distinct3600second traffic canary or900second terminal window.
// This verifies historical policy membership, not fresh dispatch authority.
func EvaluateManifestHealthWindow(program g.GitProgram, entry g.GitManifestEntry, binding HealthBinding, start time.Time, baseline, current []HealthReceipt, limits HealthLimits, now time.Time) HealthWindow {
	if g.ValidateGitProgram(program, g.Expected{Binding: binding.Binding, Realm: binding.Realm}, program.CreatedAt) != nil || binding.ProgramSHA256 != g.Digest(program) || entry.Sequence < 1 || entry.Sequence > uint64(len(program.Manifest.Entries)) || g.Digest(entry) != g.Digest(program.Manifest.Entries[entry.Sequence-1]) || entry.MinimumObservationSeconds < 120 {
		return HealthWindow{Status: "BLOCKED", ReasonCodes: []string{"MANIFEST_ENTRY_HEALTH_BINDING_INVALID"}, Binding: binding, Start: start, Definition: HealthCompletedOperation, AvailabilityBasis: "OBSERVED_HTTP_REQUEST_SUCCESS", ReceiptSHA256s: []string{}, BaselineReceiptSHA256s: []string{}}
	}
	for _, stage := range program.Stages {
		if stage.ID == entry.StageID && g.Digest(stage) == entry.StageSHA256 {
			stage.MinimumObservationSeconds = entry.MinimumObservationSeconds
			return evaluateHealthWindow(binding, stage, start, baseline, current, limits, now, true)
		}
	}
	return HealthWindow{Status: "BLOCKED", ReasonCodes: []string{"MANIFEST_ENTRY_HEALTH_BINDING_INVALID"}, Binding: binding}
}

func evaluateHealthWindow(binding HealthBinding, stage g.Stage, start time.Time, baseline, current []HealthReceipt, limits HealthLimits, now time.Time, approvedManifest bool) HealthWindow {
	return evaluateHealthWindowBaselineAt(binding, stage, start, baseline, current, limits, now, approvedManifest, start)
}

// The original entry points retain their original start-based baseline rule.
// Only the separately authenticated activation-anchor path chooses baselineAt.
func evaluateHealthWindowBaselineAt(binding HealthBinding, stage g.Stage, start time.Time, baseline, current []HealthReceipt, limits HealthLimits, now time.Time, approvedManifest bool, baselineAt time.Time) HealthWindow {
	out := HealthWindow{Status: "BLOCKED", ReasonCodes: []string{}, Binding: binding, Start: start, Definition: HealthCompletedOperation, AvailabilityBasis: "OBSERVED_HTTP_REQUEST_SUCCESS", ReceiptSHA256s: []string{}, BaselineReceiptSHA256s: []string{}}
	reason := func(code string) { out.ReasonCodes = append(out.ReasonCodes, code) }
	minimum := int64(900)
	validStage := false
	for _, s := range g.DefaultStages(20) {
		if s.Kind == stage.Kind && s.ID == stage.ID && s.Kind != g.Prepare {
			validStage = true
			minimum = s.MinimumObservationSeconds
		}
	}
	if approvedManifest {
		minimum = 120
	}
	if !binding.valid() || !validStage || stage.MinimumObservationSeconds < minimum || stage.MinimumObservationSeconds > 86400 || start.IsZero() || start.After(now) || limits.MinimumSamples < 30 || limits.MaxP95NS <= 0 || limits.MaxP99NS < limits.MaxP95NS || limits.MaxErrorRatePPM < 0 || limits.MaxErrorRatePPM > 1000000 || limits.MinAvailabilityPPM < 0 || limits.MinAvailabilityPPM > 1000000 || limits.MaxInFlight == 0 {
		reason("HEALTH_POLICY_INVALID")
		return out
	}
	out.RequiredEnd = start.Add(time.Duration(stage.MinimumObservationSeconds) * time.Second)
	b, be := population(baseline, binding, true)
	p, pe := population(current, binding, false)
	if be != nil || pe != nil {
		if errors.Is(be, errHealthClock) || errors.Is(pe, errHealthClock) {
			reason("HEALTH_CLOCK_DISCONTINUITY")
		}
		reason("HEALTH_RECEIPT_INVALID")
		return out
	}
	out.ReceiptSHA256s = p.refs
	out.BaselineReceiptSHA256s = b.refs
	out.ObservedThrough = p.last
	out.SampleCount = len(p.latencies)
	if b.schema != p.schema {
		reason("HEALTH_MEASUREMENT_REVISION_MISMATCH")
	}
	if p.schema == "2" {
		out.MeasurementRevision = healthMeasurementV2
		out.MonotonicDurationNS = &p.monotonicNS
	}
	if b.schema == "2" {
		out.BaselineMonotonicDurationNS = &b.monotonicNS
	}
	if p.last.After(now) || b.last.After(start) || p.first.Before(start) {
		reason("HEALTH_PERIOD_INVALID")
		return out
	}
	out.P95NS = healthQuantile(p.latencies, 95)
	out.P99NS = healthQuantile(p.latencies, 99)
	out.BaselineP95NS = healthQuantile(b.latencies, 95)
	out.BaselineP99NS = healthQuantile(b.latencies, 99)
	breach := false
	if p.total > 0 && p.complete {
		er := p.errors * 1000000 / p.total
		av := (p.total - p.errors) * 1000000 / p.total
		out.ErrorRatePPM = &er
		out.AvailabilityPPM = &av
		out.Accepted = &p.accepted
		out.Completed = &p.completed
		out.Rejected = &p.rejected
		out.Failed = &p.failed
		out.Backlog = &p.backlog
		out.InFlight = &p.inflight
		if er > limits.MaxErrorRatePPM {
			reason("HARD_ERROR_RATE_BREACH")
			breach = true
		}
		if av < limits.MinAvailabilityPPM {
			reason("HARD_AVAILABILITY_BREACH")
			breach = true
		}
		if p.backlog > limits.MaxBacklog || p.inflight > limits.MaxInFlight {
			reason("HARD_SATURATION_BREACH")
			breach = true
		}
	}
	if len(p.latencies) >= limits.MinimumSamples {
		if *out.P95NS > limits.MaxP95NS || *out.P99NS > limits.MaxP99NS {
			reason("HARD_LATENCY_BREACH")
			breach = true
		}
		if len(b.latencies) >= limits.MinimumSamples && b.complete && (exceedsRegression(*out.P95NS, *out.BaselineP95NS) || exceedsRegression(*out.P99NS, *out.BaselineP99NS)) {
			reason("LATENCY_REGRESSION_ABOVE_15_PERCENT")
			breach = true
		}
	}
	if len(p.latencies) < limits.MinimumSamples || len(b.latencies) < limits.MinimumSamples {
		reason("HEALTH_SAMPLES_INSUFFICIENT")
	}
	if !p.complete || !b.complete {
		reason("HEALTH_COVERAGE_UNKNOWN")
	}
	if b.first.IsZero() || b.last.Sub(b.first) < 2*time.Minute {
		reason("BASELINE_OBSERVATION_WINDOW_INCOMPLETE")
	}
	if b.schema == "2" && b.monotonicNS < int64(2*time.Minute) {
		reason("BASELINE_MONOTONIC_OBSERVATION_WINDOW_INCOMPLETE")
	}
	if b.last.IsZero() || baselineAt.Before(b.last) || baselineAt.Sub(b.last) > 5*time.Minute {
		reason("BASELINE_OBSERVATION_STALE")
	}
	if p.first.IsZero() || !p.first.Equal(start) || p.last.Before(out.RequiredEnd) || now.Before(out.RequiredEnd) {
		reason("STAGE_OBSERVATION_WINDOW_INCOMPLETE")
	}
	if p.schema == "2" && p.monotonicNS < stage.MinimumObservationSeconds*int64(time.Second) {
		reason("MONOTONIC_OBSERVATION_WINDOW_INCOMPLETE")
	}
	if breach {
		out.Status = "BREACH"
	} else if len(out.ReasonCodes) == 0 {
		out.Status = "OBSERVED"
	}
	return out
}
